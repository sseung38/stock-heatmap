import { RemovalPolicy } from "aws-cdk-lib";
import * as dynamodb from "aws-cdk-lib/aws-dynamodb";
import * as s3 from "aws-cdk-lib/aws-s3";
import { Construct } from "constructs";

/** The private data bucket (JSON snapshots) and the Watchlist table. */
export class DataResources extends Construct {
  readonly dataBucket: s3.Bucket;
  readonly table: dynamodb.Table;

  constructor(scope: Construct, id: string) {
    super(scope, id);
    this.dataBucket = new s3.Bucket(this, "DataBucket", {
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      encryption: s3.BucketEncryption.S3_MANAGED,
      enforceSSL: true,
      // Everything in it is regenerated by the refresh jobs, so it can go with the stack.
      removalPolicy: RemovalPolicy.DESTROY,
      autoDeleteObjects: true,
    });
    this.table = new dynamodb.Table(this, "Watchlist", {
      tableName: "Watchlist",
      partitionKey: { name: "userId", type: dynamodb.AttributeType.STRING },
      // 1 read / 1 write unit is inside DynamoDB's always-free tier.
      billingMode: dynamodb.BillingMode.PROVISIONED,
      readCapacity: 1,
      writeCapacity: 1,
      // Your watchlist survives even if the stack is deleted.
      removalPolicy: RemovalPolicy.RETAIN,
    });
  }
}
